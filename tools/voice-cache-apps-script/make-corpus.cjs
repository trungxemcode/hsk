// Prepare static phrase corpus from actual HSK vocabulary, examples and lesson content.
// No user history, credentials or AI-generated private text is included.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'words.js'),'utf8');
const match=source.match(/const\s+words\s*=\s*(\[[\s\S]*?\n\s*\]);/);
if(!match)throw Error('Cannot locate global HSK vocabulary array');
const words=vm.runInNewContext('('+match[1]+')',Object.create(null),{timeout:3000});
const contentByLevel={};
for(let level=1;level<=6;level++)contentByLevel[level]=JSON.parse(fs.readFileSync(path.join(root,'lesson-content-hsk'+level+'.json'),'utf8'));
const have=new Set(),items=[],counts={words:0,examples:0,lesson:0};
function add(text,source,level) {
 text=String(text||'').normalize('NFC').replace(/\s+/g,' ').trim();
 const len=[...text].length;
 if(!len||len>220||!/[\u3400-\u9fff]/u.test(text)||/[<>]/.test(text)||have.has(text))return;
 have.add(text);items.push(text);counts[source]++;
}
function extractCn(value,level){
 if(Array.isArray(value)){for(const obj of value)extractCn(obj,level);return;}
 if(!value||typeof value!=='object')return;
 for(const [key,item] of Object.entries(value)){
  if(key==='cn'&&typeof item==='string')add(item,'lesson',level);
  else if(item&&typeof item==='object')extractCn(item,level);
 }
}
for(let level=1;level<=6;level++){
 const selected=words.filter(x=>Number(x.hsk)===level);
 for(const w of selected)add(w.han,'words',level);
 for(const w of selected)add(w.exCn,'examples',level);
 extractCn(contentByLevel[level],level);
}
const output=path.join(__dirname,'corpus.json');
fs.writeFileSync(output,JSON.stringify({count:items.length,counts,items}),{encoding:'utf8'});
// Split into chunks to avoid an oversize single Apps Script function or source line.
const groups=[];for(let i=0;i<items.length;i+=300)groups.push(items.slice(i,i+300));
const code='// Autogenerated by make-corpus.cjs, HSK static learning corpus only.\n'+
'function hskWarmCorpus_(){return [].concat(\n'+
groups.map(g=>'  '+JSON.stringify(g)).join(',\n')+'\n);}\n';
fs.writeFileSync(path.join(__dirname,'WarmCorpus.gs'),code,'utf8');
console.log(JSON.stringify({total:items.length,counts,bytes:Buffer.byteLength(code),chunkCount:groups.length,sample:items.slice(0,8)}));
